// 1. Which field of results[0] carries the restaurant id from the URL?
function checkOutletCodeAndId(menus: Menu[]): string[] {
  const withResult = menus.filter((m) => m.result);
  const compare = (field: string) => {
    const matches = withResult.filter(
      (m) => String(m.result[field]) === m.restaurantId,
    ).length;
    return [code(field), String(matches), String(withResult.length - matches)];
  };
  return [
    '## 1. Restaurant id in URL vs `results[0].outletCode` / `results[0].id`',
    '',
    `Menus with results: ${withResult.length} of ${menus.length}.`,
    '',
    ...table(
      ['Field', 'Matches URL id', 'Mismatches'],
      [compare('outletCode'), compare('id')],
    ),
  ];
}

// 2. Is results[].id shared by several outlets (i.e. a brand/chain id)?
function checkIdAcrossOutlets(menus: Menu[]): string[] {
  const outletsById = groupSets(
    menus.filter((m) => m.result),
    (m) => String(m.result.id),
    (m) => String(m.result.outletCode),
  );
  const shared = [...outletsById.entries()]
    .filter(([, outlets]) => outlets.size > 1)
    .sort((a, b) => b[1].size - a[1].size);
  const namesById = new Map(
    menus
      .filter((m) => m.result)
      .map((m) => [String(m.result.id), m.result.name]),
  );
  return [
    '## 2. Does `results[].id` repeat across different `outletCode`s?',
    '',
    `Distinct ids: ${outletsById.size}. Ids with more than one outletCode: **${shared.length}**.`,
    '',
    ...(shared.length === 0
      ? []
      : table(
          ['id', 'Name (sample)', 'Distinct outletCodes'],
          shared
            .slice(0, TOP_N)
            .map(([id, outlets]) => [
              id,
              namesById.get(id),
              String(outlets.size),
            ]),
        )),
  ];
}

// 3. Duplicate item_ids: same restaurant (other categories) or across restaurants?
function checkDuplicateItemIds(menus: Menu[]): string[] {
  const occurrences = new Map<
    string,
    { restaurant: string; category: string }[]
  >();
  for (const m of menus) {
    for (const category of m.result?.category ?? []) {
      for (const item of category.items ?? []) {
        const key = String(item.item_id);
        const list = occurrences.get(key) ?? [];
        list.push({
          restaurant: m.restaurantId,
          category: category.category_name,
        });
        occurrences.set(key, list);
      }
    }
  }

  const duplicated = [...occurrences.values()].filter((o) => o.length > 1);
  let sameRestaurant = 0;
  let acrossRestaurants = 0;
  let sameCategoryRepeat = 0; // same restaurant + same category name
  const categoryHits = new Map<string, number>();
  for (const occ of duplicated) {
    const restaurants = new Set(occ.map((o) => o.restaurant));
    if (restaurants.size === 1) sameRestaurant++;
    else acrossRestaurants++;
    const pairs = new Set(occ.map((o) => `${o.restaurant}|${o.category}`));
    if (pairs.size < occ.length) sameCategoryRepeat++;
    for (const o of occ) increment(categoryHits, o.category);
  }

  return [
    '## 3. Duplicate `item_id`s',
    '',
    ...table(
      ['Metric', 'Count'],
      [
        ['Distinct item_ids', String(occurrences.size)],
        ['item_ids appearing more than once', String(duplicated.length)],
        ['…all occurrences in one restaurant', String(sameRestaurant)],
        ['…spread across restaurants', String(acrossRestaurants)],
        [
          '…repeated inside the same restaurant + category name',
          String(sameCategoryRepeat),
        ],
      ],
    ),
    '',
    `Top ${TOP_N} category names containing duplicated item_ids (occurrences):`,
    '',
    ...table(['Category name', 'Occurrences'], topEntries(categoryHits)),
  ];
}

// 4. Duplicate category_ids: same restaurant or across restaurants?
function checkDuplicateCategoryIds(menus: Menu[]): string[] {
  const restaurantsByCategory = new Map<string, string[]>();
  const namesByCategory = new Map<string, Set<string>>();
  for (const m of menus) {
    for (const category of m.result?.category ?? []) {
      const key = String(category.category_id);
      restaurantsByCategory.set(key, [
        ...(restaurantsByCategory.get(key) ?? []),
        m.restaurantId,
      ]);
      namesByCategory.set(
        key,
        (namesByCategory.get(key) ?? new Set()).add(category.category_name),
      );
    }
  }
  const duplicated = [...restaurantsByCategory.entries()].filter(
    ([, r]) => r.length > 1,
  );
  const across = duplicated.filter(([, r]) => new Set(r).size > 1);
  return [
    '## 4. Duplicate `category_id`s',
    '',
    ...table(
      ['Metric', 'Count'],
      [
        ['Distinct category_ids', String(restaurantsByCategory.size)],
        ['category_ids appearing more than once', String(duplicated.length)],
        [
          '…all occurrences in one restaurant',
          String(duplicated.length - across.length),
        ],
        ['…spread across restaurants', String(across.length)],
      ],
    ),
    '',
    `Sample (up to ${TOP_N}):`,
    '',
    ...table(
      ['category_id', 'Occurrences', 'Distinct restaurants', 'Names'],
      duplicated
        .slice(0, TOP_N)
        .map(([id, r]) => [
          id,
          String(r.length),
          String(new Set(r).size),
          [...namesByCategory.get(id)].join(', '),
        ]),
    ),
  ];
}

// 5. Restaurant listing: overlap between areas, and coverage by menus.
async function checkRestaurantListing(
  db: Db,
  batchSize: number,
  menus: Menu[],
): Promise<string[]> {
  const areasByRestaurant = new Map<string, Set<string>>();
  let unparsed = 0;
  const cursor = db
    .collection(RESTAURANTS)
    .find({}, { projection: { 'params.areaSlug': 1, 'payload.results': 1 } })
    .batchSize(batchSize);
  for await (const doc of cursor) {
    for (const r of doc.payload?.results ?? []) {
      const id = parseRestaurantId(r.restaurant_url);
      if (!id) {
        unparsed++;
        continue;
      }
      const areas = areasByRestaurant.get(id) ?? new Set<string>();
      areas.add(doc.params?.areaSlug);
      areasByRestaurant.set(id, areas);
    }
  }

  const allAreas = new Set(
    [...areasByRestaurant.values()].flatMap((a) => [...a]),
  );
  const inAllAreas = [...areasByRestaurant.values()].filter(
    (a) => a.size === allAreas.size,
  ).length;
  const menuIds = new Set(menus.map((m) => m.restaurantId));
  const menuIdsWithResults = new Set(
    menus.filter((m) => m.result).map((m) => m.restaurantId),
  );
  const listed = [...areasByRestaurant.keys()];
  return [
    '## 5. Restaurant listing vs areas and menus',
    '',
    ...table(
      ['Metric', 'Count'],
      [
        ['Areas in listing', `${allAreas.size} (${[...allAreas].join(', ')})`],
        ['Distinct restaurant ids in listing', String(areasByRestaurant.size)],
        ['URLs without a parseable id', String(unparsed)],
        ['…listed in all areas', String(inAllAreas)],
        [
          '…also in menus (any menu doc)',
          String(listed.filter((id) => menuIds.has(id)).length),
        ],
        [
          '…also in menus with results',
          String(listed.filter((id) => menuIdsWithResults.has(id)).length),
        ],
        ['Distinct restaurant ids in menus', String(menuIds.size)],
      ],
    ),
  ];
}

// 6. Slugs that map to more than one location_id.
async function checkLocationSlugs(
  db: Db,
  batchSize: number,
): Promise<string[]> {
  const idsBySlug = new Map<string, Set<number>>();
  const namesById = new Map<number, string>();
  const cursor = db
    .collection(LOCATIONS)
    .find({}, { projection: { 'payload.results': 1 } })
    .batchSize(batchSize);
  for await (const doc of cursor) {
    for (const loc of doc.payload?.results ?? []) {
      idsBySlug.set(
        loc.location_slug,
        (idsBySlug.get(loc.location_slug) ?? new Set()).add(loc.location_id),
      );
      namesById.set(loc.location_id, loc.location_name);
    }
  }
  const ambiguous = [...idsBySlug.entries()]
    .filter(([, ids]) => ids.size > 1)
    .sort(([a], [b]) => a.localeCompare(b));
  return [
    '## 6. Location slugs mapping to more than one `location_id`',
    '',
    `Slugs: ${idsBySlug.size}. Ambiguous: **${ambiguous.length}**.`,
    '',
    ...table(
      ['Slug', 'location_ids (name)'],
      ambiguous.map(([slug, ids]) => [
        code(slug),
        [...ids].map((id) => `${id} (${namesById.get(id)})`).join(', '),
      ]),
    ),
  ];
}

// 7. Are totalReviews / item ratings effectively unused?
function checkReviewsAndRatings(menus: Menu[]): string[] {
  const reviews = new Map<string, number>();
  const ratings = new Map<string, number>();
  for (const m of menus) {
    if (!m.result) continue;
    increment(reviews, String(m.result.totalReviews));
    for (const category of m.result.category ?? []) {
      for (const item of category.items ?? []) {
        increment(ratings, String(item.rating));
      }
    }
  }
  const distribution = (counts: Map<string, number>) => {
    const total = sum(counts);
    return [...counts.entries()]
      .sort((a, b) => b[1] - a[1])
      .map(([value, n]) => [value, String(n), pct(n, total)]);
  };
  return [
    '## 7. `totalReviews` and item `rating`',
    '',
    '`results[].totalReviews`:',
    '',
    ...table(['Value', 'Count', 'Share'], distribution(reviews)),
    '',
    '`results[].category[].items[].rating`:',
    '',
    ...table(['Value', 'Count', 'Share'], distribution(ratings)),
  ];
}

// 8. Restaurant Address values not found among location names.
function checkAddresses(menus: Menu[], locationNames: Set<string>): string[] {
  const unmatched = new Map<string, number>();
  let total = 0;
  for (const m of menus) {
    if (!m.result) continue;
    total++;
    const address = m.result['Restaurant Address'];
    if (!locationNames.has(normalize(address))) {
      increment(unmatched, JSON.stringify(address));
    }
  }
  return [
    '## 8. `Restaurant Address` values not matching any `location_name`',
    '',
    'Compared after trim + lowercase.',
    `Unmatched menus: **${sum(unmatched)}** of ${total};` +
      ` distinct unmatched values: **${unmatched.size}**.`,
    '',
    ...table(
      ['Address (JSON)', 'Menus'],
      [...unmatched.entries()]
        .sort((a, b) => b[1] - a[1])
        .map(([value, n]) => [code(value), String(n)]),
    ),
  ];
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function parseRestaurantId(url: unknown): string | undefined {
  return typeof url === 'string'
    ? url.match(RESTAURANT_ID_IN_URL)?.[1]
    : undefined;
}

function normalize(value: unknown): string {
  return String(value ?? '')
    .trim()
    .toLowerCase();
}

function groupSets<T>(
  items: T[],
  key: (item: T) => string,
  value: (item: T) => string,
): Map<string, Set<string>> {
  const groups = new Map<string, Set<string>>();
  for (const item of items) {
    const k = key(item);
    groups.set(k, (groups.get(k) ?? new Set()).add(value(item)));
  }
  return groups;
}

function increment(map: Map<string, number>, key: string): void {
  map.set(key, (map.get(key) ?? 0) + 1);
}

function sum(map: Map<string, number>): number {
  let total = 0;
  for (const n of map.values()) total += n;
  return total;
}

function topEntries(map: Map<string, number>): string[][] {
  return [...map.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, TOP_N)
    .map(([k, n]) => [k, String(n)]);
}

function pct(part: number, whole: number): string {
  return whole === 0 ? '—' : `${((part / whole) * 100).toFixed(1)}%`;
}

function code(text: string): string {
  return '`' + text.replace(/`/g, "'") + '`';
}

function table(headers: string[], rows: string[][]): string[] {
  const escape = (cell: string) => String(cell).replace(/\|/g, '\\|');
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(escape).join(' | ')} |`),
  ];
}

