import 'dotenv/config';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { Db, Document, MongoClient } from 'mongodb';
import { envSchema } from '../src/config/env.schema';

// Read-only checks of hypotheses raised by docs/profile.md. Prints the
// report and writes it to docs/verify.md.

const OUTPUT_PATH = join(__dirname, '..', 'docs', 'verify.md');
const MENUS = 'compero-xbyte.xbyte-raw-menus';
const RESTAURANTS = 'compero-xbyte.xbyte-raw-restaurants';
const LOCATIONS = 'compero-xbyte.xbyte-raw-locations';
const RESTAURANT_ID_IN_URL = /\/restaurant\/(\d+)\//;
const TOP_N = 15;

interface Menu {
  restaurantId: string; // parsed from params.restaurant_url
  result?: Document; // payload.results[0]
}

async function main(): Promise<void> {
  const { MONGO_RAW_URI, BATCH_SIZE } = envSchema
    .pick({ MONGO_RAW_URI: true, BATCH_SIZE: true })
    .parse(process.env);

  const client = await MongoClient.connect(MONGO_RAW_URI);
  try {
    const db = client.db();
    const menus = await loadMenus(db, BATCH_SIZE);
    const locationNames = await loadLocationNames(db, BATCH_SIZE);

    const sections = [
      checkOutletCodeAndId(menus),
      checkIdAcrossOutlets(menus),
      checkDuplicateItemIds(menus),
      checkDuplicateCategoryIds(menus),
      await checkRestaurantListing(db, BATCH_SIZE, menus),
      await checkLocationSlugs(db, BATCH_SIZE),
      checkReviewsAndRatings(menus),
      checkAddresses(menus, locationNames),
    ];
    const markdown = [
      `# Hypothesis checks: \`${db.databaseName}\``,
      '',
      'Generated by `scripts/verify-hypotheses.ts`. Restaurant key in menus =',
      'numeric id parsed from `params.restaurant_url` (`/restaurant/{id}/`).',
      '',
      ...sections.flatMap((s) => [...s, '']),
    ].join('\n');

    console.log(markdown);
    await writeFile(OUTPUT_PATH, markdown);
    console.log(`Wrote ${OUTPUT_PATH}`);
  } finally {
    await client.close();
  }
}

// ---------------------------------------------------------------------------
// Loading
// ---------------------------------------------------------------------------

async function loadMenus(db: Db, batchSize: number): Promise<Menu[]> {
  const menus: Menu[] = [];
  const cursor = db
    .collection(MENUS)
    .find(
      {},
      { projection: { 'params.restaurant_url': 1, 'payload.results': 1 } },
    )
    .batchSize(batchSize);
  for await (const doc of cursor) {
    menus.push({
      restaurantId: parseRestaurantId(doc.params?.restaurant_url),
      result: doc.payload?.results?.[0],
    });
  }
  return menus;
}

async function loadLocationNames(
  db: Db,
  batchSize: number,
): Promise<Set<string>> {
  const names = new Set<string>();
  const cursor = db
    .collection(LOCATIONS)
    .find({}, { projection: { 'payload.results.location_name': 1 } })
    .batchSize(batchSize);
  for await (const doc of cursor) {
    for (const loc of doc.payload?.results ?? []) {
      names.add(normalize(loc.location_name));
    }
  }
  return names;
}

